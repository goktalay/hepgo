"""Ürün Yönetimi: yeni ürün (kod, ad, tip), iç içe ürün ağacı, reçete, resim ve G-code; mevcut yapının taşınması.

Çalıştırma: .venv/bin/python -m tests.test_product_bom
"""
import os
import tempfile

tmp = tempfile.mkdtemp()
os.environ.update(CAYMAZ_DATA_DIR=tmp, CAYMAZ_PRINTER_POLL='0',
                  CAYMAZ_ADMIN_USERNAME='admin@test', CAYMAZ_ADMIN_PASSWORD='admin-sifre-1')

from fastapi.testclient import TestClient  # noqa: E402

from app.main import app  # noqa: E402

GCODE = '''; generated by Test Slicer
; estimated printing time (normal mode) = 1h 2m 3s
; filament used [g] = 12.5
; filament used [mm] = 4000
; filament_type = PETG
G28
M83
;LAYER_CHANGE
G1 Z0.2 F600
;TYPE:Outer wall
G1 X0 Y0
G1 X10 Y0 E1
G1 X10 Y10 E1
G1 X0 Y10 E1
G1 X0 Y0 E1
;LAYER_CHANGE
G1 Z0.4
G1 X10 Y0 E1
G1 X10 Y10 E1
'''


def ok(r, code=200):
    assert r.status_code == code, (r.status_code, r.text)
    return r.json()


def main():
    with TestClient(app) as a:
        ok(a.post('/api/auth/login', json={'username': 'admin@test', 'password': 'admin-sifre-1'}))
        products = ok(a.get('/api/products'))
        # Taşıma: basılı parçalar yarı mamul; YEDEK_PARCA / HAMMADDE tipinde henüz şemalı ürün yok
        assert {p['type'] for p in products if p['stocked']} == {'YARI_MAMUL'}
        cyz = next(p for p in products if p['code'] == 'CYZ')
        tree = ok(a.get(f'/api/products/{cyz["id"]}/tree'))
        assert [n['code'] for n in tree['children']] == ['SLK', 'SGK', 'GVD', 'ELK']

        # Yeni ürün: kod, ad, tip → id (sayfası açılır)
        assert a.post('/api/products', json={'code': 'x', 'name': '', 'type': 'MAMUL'}).status_code == 400
        assert a.post('/api/products', json={'code': 'CYZ', 'name': 'Tekrar', 'type': 'MAMUL'}).status_code == 400
        assert a.post('/api/products', json={'code': 'ABC', 'name': 'X', 'type': 'BASKA'}).status_code == 400
        m = ok(a.post('/api/products', json={'code': 'dm-1', 'name': 'Deneme Mamul', 'type': 'MAMUL'}))['id']
        y1 = ok(a.post('/api/products', json={'code': 'YM-1', 'name': 'Kanat Grubu', 'type': 'YARI_MAMUL'}))['id']
        y2 = ok(a.post('/api/products', json={'code': 'YM-2', 'name': 'Kanat Ucu', 'type': 'YARI_MAMUL'}))['id']
        vida = ok(a.post('/api/products', json={'code': 'VD-M3', 'name': 'M3 Vida', 'type': 'YEDEK_PARCA'}))['id']
        fil = ok(a.post('/api/products', json={'code': 'HM-PLA', 'name': 'PLA Filament', 'type': 'HAMMADDE', 'unit': 'g'}))['id']
        pm = ok(a.get(f'/api/products/{m}'))
        assert (pm['code'], pm['type'], pm['role'], pm['orderable'], pm['type_label']) == ('DM-1', 'MAMUL', 'custom', 0, 'Mamul')
        assert ok(a.get(f'/api/products/{vida}'))['unit'] == 'adet'
        # şemasız ürünün siparişi açılamaz; mamul listesi (planlayıcı, stok) etkilenmez
        assert a.post('/api/orders', json={'product_id': m}).status_code == 400
        assert a.put(f'/api/products/{m}', json={'name': 'Deneme Mamul', 'serial': 'DM-1', 'code': 'DM-1', 'queue_prefix': 'DM1',
                                                  'orderable': True}).status_code == 400

        # Ürün ağacı: iç içe yarı mamuller; döngü ve tip kontrolü
        ok(a.post(f'/api/products/{m}/bom', json={'child_id': y1, 'qty': 2}))
        ok(a.post(f'/api/products/{y1}/bom', json={'child_id': y2, 'qty': 3}))
        assert a.post(f'/api/products/{y2}/bom', json={'child_id': y1, 'qty': 1}).status_code == 400   # döngü
        assert a.post(f'/api/products/{y1}/bom', json={'child_id': y1, 'qty': 1}).status_code == 400
        assert a.post(f'/api/products/{m}/bom', json={'child_id': vida, 'qty': 1}).status_code == 400   # yedek parça reçeteye
        assert a.post(f'/api/products/{m}/bom', json={'child_id': y1, 'qty': 1}).status_code == 400     # zaten ekli
        assert a.post(f'/api/products/{vida}/bom', json={'child_id': y1, 'qty': 1}).status_code == 400
        t = ok(a.get(f'/api/products/{m}/tree'))
        assert (t['children'][0]['code'], t['children'][0]['qty'], t['children'][0]['children'][0]['code'],
                t['children'][0]['children'][0]['qty']) == ('YM-1', 2, 'YM-2', 3)
        ok(a.put(f'/api/products/{m}/bom/{y1}', json={'qty': 4}))
        assert ok(a.get(f'/api/products/{y2}'))['used_in'][0]['code'] == 'YM-1'

        # Reçete: yedek parça / hammadde; toplam ihtiyaç ağaç adetleriyle çarpılır (4 × 3 × 10 vida = 120)
        ok(a.post(f'/api/products/{y2}/recipe', json={'item_id': vida, 'qty': 10}))
        ok(a.post(f'/api/products/{y1}/recipe', json={'item_id': fil, 'qty': 25.5, 'note': 'kaplama'}))
        ok(a.post(f'/api/products/{m}/recipe', json={'item_id': vida, 'qty': 4}))
        assert a.post(f'/api/products/{m}/recipe', json={'item_id': y1, 'qty': 1}).status_code == 400
        assert a.post(f'/api/products/{m}/recipe', json={'item_id': vida, 'qty': 0}).status_code == 400
        r = ok(a.get(f'/api/products/{m}/recipe'))
        assert [(x['code'], x['qty']) for x in r['items']] == [('VD-M3', 4)]
        assert {x['code']: x['qty'] for x in r['total']} == {'VD-M3': 124, 'HM-PLA': 102}
        ok(a.post(f'/api/products/{m}/recipe', json={'item_id': vida, 'qty': 6}))   # güncelleme
        assert ok(a.get(f'/api/products/{m}/recipe'))['items'][0]['qty'] == 6
        ok(a.delete(f'/api/products/{m}/recipe/{vida}'))
        assert [x['code'] for x in ok(a.get(f'/api/products/{vida}'))['used_in_recipes']] == ['YM-2']
        # Sarf malzeme reçeteye eklenebilir (demirbaş eklenemez)
        srf = ok(a.post('/api/products', json={'code': 'SF-1', 'name': 'Temizlik Bezi', 'type': 'SARF', 'unit': 'adet'}))['id']
        dmb = ok(a.post('/api/products', json={'code': 'DB-1', 'name': 'Tezgah', 'type': 'DEMIRBAS', 'unit': 'adet'}))['id']
        ok(a.post(f'/api/products/{y1}/recipe', json={'item_id': srf, 'qty': 2}))
        assert 'SF-1' in {x['code'] for x in ok(a.get(f'/api/products/{y1}/recipe'))['items']}
        assert a.post(f'/api/products/{y1}/recipe', json={'item_id': dmb, 'qty': 1}).status_code == 400   # demirbaş reçeteye eklenemez

        # Resim (2B üstten görünüm)
        png = bytes.fromhex('89504e470d0a1a0a0000000d4948445200000001000000010806000000'
                            '1f15c4890000000d49444154789c6360000002000154a24f5d0000000049454e44ae426082')
        img = ok(a.post(f'/api/products/{y1}/image', files={'file': ('ust.png', png, 'image/png')}))['image']
        assert a.get(f'/api/files/{img}').status_code == 200
        assert a.post(f'/api/products/{y1}/image', files={'file': ('x.svg', b'<svg/>', 'image/svg+xml')}).status_code == 400
        ok(a.delete(f'/api/products/{y1}/image'))

        # G-code (parça parça yükleme) → bilgiler ve 3B yol
        data = GCODE.encode()
        up = ok(a.post('/api/uploads', json={'kind': 'gcode', 'file_name': 'kanat ucu.gcode', 'size': len(data)}))
        ok(a.put(f'/api/uploads/{up["upload_id"]}?offset=0', content=data))
        res = ok(a.post(f'/api/products/{y2}/gcode', json={'upload_id': up['upload_id']}))
        p2 = ok(a.get(f'/api/products/{y2}'))
        assert p2['gcode_file'] == 'gcode/kanat ucu.gcode' and p2['gcode_preview'], p2['gcode_file']
        assert res['filament_g'] == 12.5
        ok(a.delete(f'/api/products/{y2}/gcode'))
        assert not ok(a.get(f'/api/products/{y2}'))['gcode_preview']

        # Tip yalnızca Ürün Yönetimi'nden açılan üründe değişir; şemalı ürün silinemez
        ok(a.put(f'/api/products/{y2}', json={'name': 'Kanat Ucu', 'serial': 'YM-2', 'code': 'YM-2', 'queue_prefix': 'YM2', 'type': 'MAMUL'}))
        assert ok(a.get(f'/api/products/{y2}'))['type'] == 'MAMUL'
        assert a.delete(f'/api/products/{cyz["id"]}').status_code == 400
        ok(a.delete(f'/api/products/{y2}'))
        assert ok(a.get(f'/api/products/{y1}/tree'))['children'] == []
        assert a.get(f'/api/products/{y2}').status_code == 404
        # liste ve seçimler
        assert any(p['code'] == 'HM-PLA' for p in ok(a.get('/api/products/options')))
        assert any(p['code'] == 'DM-1' for p in ok(a.get('/api/products')))
    print('Ürün ağacı / reçete testleri geçti.')


if __name__ == '__main__':
    main()
